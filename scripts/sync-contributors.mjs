#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import process from 'node:process';

const OWNER = 'Vijay431';
const REPO = 'yt-autolike';
const CONTRIBUTORS_FILE = 'CONTRIBUTORS.md';
const API_URL = `https://api.github.com/repos/${OWNER}/${REPO}/contributors?per_page=100`;

const FALLBACK_CONTRIBUTORS = [
  {
    login: 'Vijay431',
    html_url: 'https://github.com/Vijay431',
    contributions: null,
  },
];

const AI_ACKNOWLEDGEMENTS = [
  {
    name: 'Claude',
    note: 'for collaborative implementation, review, and product-shaping assistance.',
  },
  {
    name: 'Codex',
    note: 'for code editing, validation, release preparation, and repository maintenance help.',
  },
  {
    name: 'Antigravity',
    note: 'for agent-assisted development workflows and iteration support.',
  },
  {
    name: 'Gemini',
    note: 'for additional coding, research, and reasoning support.',
  },
];

const args = new Set(process.argv.slice(2));
const checkMode = args.has('--check');
const noFallback = args.has('--no-fallback');

async function fetchContributors() {
  const headers = {
    Accept: 'application/vnd.github+json',
    'User-Agent': `${REPO}-contributor-sync`,
    'X-GitHub-Api-Version': '2022-11-28',
  };

  if (process.env.GITHUB_TOKEN) {
    headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  }

  const response = await fetch(API_URL, { headers });

  if (!response.ok) {
    const retryAfter = response.headers.get('retry-after');
    const rateLimitReset = response.headers.get('x-ratelimit-reset');
    const retryHint = retryAfter
      ? ` Retry after ${retryAfter} seconds.`
      : rateLimitReset
        ? ` Rate limit resets at ${new Date(Number(rateLimitReset) * 1000).toISOString()}.`
        : '';

    throw new Error(`GitHub contributors API returned ${response.status}.${retryHint}`);
  }

  const contributors = await response.json();

  if (!Array.isArray(contributors)) {
    throw new Error('GitHub contributors API returned an unexpected response.');
  }

  return contributors
    .filter((contributor) => contributor?.login && contributor?.html_url)
    .filter((contributor) => !contributor.login.endsWith('[bot]'))
    .map((contributor) => ({
      login: contributor.login,
      html_url: contributor.html_url,
      contributions: Number.isFinite(contributor.contributions) ? contributor.contributions : null,
    }))
    .sort((first, second) => first.login.localeCompare(second.login, 'en'));
}

async function getContributors() {
  try {
    const contributors = await fetchContributors();

    if (contributors.length === 0) {
      throw new Error('GitHub contributors API returned no contributors.');
    }

    return { contributors, usedFallback: false, warning: null };
  } catch (error) {
    if (noFallback) {
      throw error;
    }

    return {
      contributors: FALLBACK_CONTRIBUTORS,
      usedFallback: true,
      warning: error instanceof Error ? error.message : String(error),
    };
  }
}

function renderContributor(contributor) {
  const contributionText =
    contributor.contributions === null
      ? ''
      : ` (${contributor.contributions} contribution${contributor.contributions === 1 ? '' : 's'})`;

  return `- [@${contributor.login}](${contributor.html_url})${contributionText}`;
}

function renderContributorsFile({ contributors, usedFallback, warning }) {
  const fallbackNote = usedFallback
    ? [
        '',
        '> Generated with deterministic fallback data because the GitHub API was unavailable.',
        `> Last API error: ${warning}`,
      ].join('\n')
    : '';

  return `# Contributors

Thank you to everyone who helps make YT AutoLike better for creators, viewers, and browser-extension users.

<!-- This file is generated by scripts/sync-contributors.mjs. Do not edit generated sections by hand. -->

## Human GitHub Contributors

${contributors.map(renderContributor).join('\n')}${fallbackNote}

## AI and Tooling Acknowledgements

These tools have helped with implementation, review, documentation, packaging, and maintenance. Human contributors remain responsible for project direction, code review, and release decisions.

${AI_ACKNOWLEDGEMENTS.map(({ name, note }) => `- **${name}** ${note}`).join('\n')}
`;
}

async function main() {
  const contributorData = await getContributors();
  const nextContent = renderContributorsFile(contributorData);

  if (checkMode) {
    const currentContent = await readFile(CONTRIBUTORS_FILE, 'utf8').catch((error) => {
      if (error.code === 'ENOENT') {
        return null;
      }

      throw error;
    });

    if (currentContent !== nextContent) {
      console.error(`${CONTRIBUTORS_FILE} is out of date. Run node scripts/sync-contributors.mjs.`);
      process.exitCode = 1;
      return;
    }

    console.log(`${CONTRIBUTORS_FILE} is up to date.`);
    return;
  }

  await writeFile(CONTRIBUTORS_FILE, nextContent);

  if (contributorData.usedFallback) {
    console.warn(`Used fallback contributor data: ${contributorData.warning}`);
  }

  console.log(`Wrote ${CONTRIBUTORS_FILE}.`);
}

await main();
